import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import library from '../src/mastra/photo-library.ts'

// Run with the approved send-safe library directory as the sole argument.
const directory = process.argv[2]
if (!directory) throw new Error('Usage: node scripts/bundle-photo-assets.mjs <approved-library-directory>')
const assets = {}
for (const photo of [...library.photos, ...library.rapport]) {
  assets[photo.file] = (await readFile(join(directory, photo.file))).toString('base64')
}
await writeFile(new URL('../src/mastra/photo-assets.ts', import.meta.url),
  '// Generated by scripts/bundle-photo-assets.mjs from the approved send-safe JPEG library.\n' +
  '// Static import keeps these exact bytes inside the native server bundle.\n' +
  `export const bundledPhotos: Record<string, string> = ${JSON.stringify(assets, null, 2)}\n`)
console.log(`Bundled ${Object.keys(assets).length} approved JPEGs`)
